const untranslatedNodes = new WeakMap();
const attrOriginals = new WeakMap();
const FIELDS = ['title', 'aria-label', 'placeholder', 'data-tooltip', 'aria-valuetext'];
const USER_CONTENT = '.card-title, .detail-heading h2, .person-name, .original-title, .synopsis, .genre-chips, .play-media-title, .saved-media strong, .saved-list-row strong, .search-list-result strong, .source-name, .connection-card strong, .cast-member small, [data-i18n-ignore]';
function inUserData(node) {
  const parent = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
  return !!(parent && parent.closest(USER_CONTENT));
}
function translateNode(node) {
  if (!node || inUserData(node)) return;
  if (node.nodeType === Node.TEXT_NODE) {
    const value = node.nodeValue;
    const original = untranslatedNodes.get(node);
    if (original && original.english === value) return;
    const translated = tr(value);
    untranslatedNodes.set(node, {original: value, english: translated});
    if (translated !== value) node.nodeValue = translated;
  } else if (node.nodeType === Node.ELEMENT_NODE) {
    let originals = attrOriginals.get(node);
    if (!originals) { originals = new Map(); attrOriginals.set(node, originals); }
    for (const key of FIELDS) {
      if (!node.hasAttribute(key)) continue;
      const value = node.getAttribute(key);
      const old = originals.get(key);
      if (old && old.english === value) continue;
      const translated = tr(value);
      originals.set(key, {original: value, english: translated});
      if (translated !== value) node.setAttribute(key, translated);
    }
    for (const child of node.childNodes) translateNode(child);
  }
}
function updateDOM() {
  if (language !== 'en') return;
  translateNode(document.body);
}
export function startI18n() {
  document.documentElement.lang = language;
  const controls = Array.from(document.querySelectorAll('[data-language-select]'));
  for (const select of controls) {
    select.value = language;
    select.addEventListener('change', () => {
      const target = select.value;
      if (target !== 'fr' && target !== 'en') return;
      try { localStorage.setItem(KEY, target); } catch { /* storage is optional */ }
      window.location.reload();
    });
  }
  updateDOM();
  const observer = new MutationObserver(records => {
    if (language !== 'en') return;
    for (const record of records) {
      if (record.type === 'characterData') translateNode(record.target);
      else if (record.type === 'attributes') translateNode(record.target);
      else for (const added of record.addedNodes) translateNode(added);
    }
  });
  observer.observe(document.body, {
    subtree: true, childList: true, characterData: true, attributes: true,
    attributeFilter: FIELDS
  });
}
