function translate(str) {
  if (Object.prototype.hasOwnProperty.call(EN, str)) return EN[str];
  for (const [pattern, format] of PATTERNS) {
    if (pattern.test(str)) return str.replace(pattern, (...args) => format(...args));
  }
  return str;
}
export function tr(value) {
  if (language !== 'en') return String(value ?? '');
  const str = String(value ?? '');
  const match = /^(\s*)([\s\S]*?)(\s*)$/.exec(str);
  return match[1] + translate(match[2]) + match[3];
}
